#!/bin/sh
# Writes libGL.a with an empty function for every OpenGL call in the game's
# sources: sh glstubs.sh <src dir> <out dir>
#
# The terminal-only build links this instead of the system's libGL, so the
# binary needs no OpenGL library at all. Terminal mode never calls OpenGL
# (the game's GL helpers return at once in it), so what the functions do
# never matters; each just returns 0.
set -eu
src=$1
out=$2
mkdir -p "$out"
c="$out/glstubs.c"

{
  echo "/* Generated by asciiverse/glstubs.sh: OpenGL stand-ins for the terminal-only build. */"
  grep -rhoE '\bgl[A-Z][A-Za-z0-9_]*[[:space:]]*\(' "$src" --include='*.cpp' --include='*.hpp' \
    | sed -E 's/[[:space:]]*\($//' | sort -u \
    | while read -r name; do
        echo "long $name(void) { return 0; }"
      done
} > "$c"

${CC:-cc}${CC_ARCH:+ -arch $CC_ARCH} -O2 -fPIC -c "$c" -o "$out/glstubs.o"
rm -f "$out/libGL.a"
ar rcs "$out/libGL.a" "$out/glstubs.o"
