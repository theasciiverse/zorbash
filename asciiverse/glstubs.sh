#!/bin/sh
# Writes libGL.a with an empty function for every OpenGL call in the game:
#   sh glstubs.sh <src dir> <out dir> [<object dir>]
# The names come from the sources (calls, and macros naming another GL
# function, like glBindFramebuffer_EXT), and from the compiled objects'
# undefined gl* symbols when an object folder is given.
#
# The terminal-only build links this instead of the system's libGL, so the
# binary needs no OpenGL library at all. Terminal mode never calls OpenGL
# (the game's GL helpers return at once in it), so what the functions do
# never matters; each just returns 0.
set -eu
src=$1
out=$2
objs=${3:-}
mkdir -p "$out"
c="$out/glstubs.c"

names() {
  grep -rhoE '\bgl[A-Z][A-Za-z0-9_]*[[:space:]]*\(' "$src" --include='*.cpp' --include='*.hpp' \
    | sed -E 's/[[:space:]]*\($//'
  grep -rhoE '#define[[:space:]]+gl[A-Za-z0-9_]+[[:space:]]+gl[A-Z][A-Za-z0-9_]*' "$src" --include='*.hpp' \
    | awk '{print $3}'
  if [ -n "$objs" ]; then
    nm -u "$objs"/*.o 2>/dev/null | awk '$1 == "U" && $2 ~ /^gl[A-Z]/ {print $2}'
  fi
}

{
  echo "/* Generated by asciiverse/glstubs.sh: OpenGL stand-ins for the terminal-only build. */"
  names | sort -u | while read -r name; do
    echo "long $name(void) { return 0; }"
  done
} > "$c"

${CC:-cc}${CC_ARCH:+ -arch $CC_ARCH} -O2 -fPIC -c "$c" -o "$out/glstubs.o"
rm -f "$out/libGL.a"
ar rcs "$out/libGL.a" "$out/glstubs.o"
